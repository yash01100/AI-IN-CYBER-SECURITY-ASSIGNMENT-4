"""## Q5. Responsible alert generation (10 marks)
The following implements the supplied skeleton: Suspicious → High; otherwise confidence < 0.70 → Medium; otherwise Low. High and Medium require human review. Reasons are observable rule-based warning indicators, not extracted decision-tree paths. Several indicators alone do not escalate a Normal prediction in this skeleton; production policies would need explicit escalation rules.
"""

def numeric_reason(row):
    reasons = []
    if row['failed_logins'] >= 5: reasons.append('many failed logins')
    if row['new_device'] == 1: reasons.append('new device')
    if row['login_hour'] < 6 or row['login_hour'] > 22: reasons.append('unusual login time')
    if row['download_mb'] >= 500: reasons.append('large data download')
    return ', '.join(reasons) if reasons else 'no strong warning'

def make_alert(row):
    if row['prediction'] == 'Suspicious':
        severity, action = 'High', 'Verify, contain if required, and report after human review.'
    elif row['confidence'] < 0.70:
        severity, action = 'Medium', 'Send for analyst review before action.'
    else:
        severity, action = 'Low', 'Continue normal monitoring.'
    return severity, numeric_reason(row), action, 'Yes' if severity in ['High','Medium'] else 'No'

samples[['severity','reason','recommended_action','human_review']] = pd.DataFrame(
    samples.apply(make_alert, axis=1).tolist(), index=samples.index)
final_alerts = samples[['masked_account','prediction','confidence','severity','reason','recommended_action','human_review']].copy()
display(final_alerts.round({'confidence':3}))
assert final_alerts.loc[final_alerts.severity.isin(['High','Medium']), 'human_review'].eq('Yes').all()
assert 'account_id' not in final_alerts and 'ip_address' not in final_alerts
final_alerts.to_csv('responsible_alerts.csv', index=False)
print('Limitation: a small dataset and uncalibrated tree probabilities cannot establish real-world attack likelihood. Human context and validation are needed.')

