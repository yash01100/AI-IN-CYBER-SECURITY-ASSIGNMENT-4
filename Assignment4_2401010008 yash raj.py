from pathlib import Path
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.impute import SimpleImputer
from sklearn.tree import DecisionTreeClassifier
from sklearn.pipeline import Pipeline
from sklearn.metrics import accuracy_score, confusion_matrix

data_path = Path('simple_login_activity.csv')
if not data_path.exists():
    from google.colab import files
    files.upload()
df = pd.read_csv(data_path)
features = ['failed_logins', 'login_hour', 'new_device', 'download_mb']
print('Rows:', len(df), '| Duplicate rows:', df.duplicated().sum())
print('Missing values:')
display(df[features + ['label']].isna().sum().to_frame('missing'))
df = df.drop_duplicates().copy()
print('Rows after removing exact duplicate records:', len(df))
assert df['label'].notna().all()
assert set(df['label']) == {'Normal', 'Suspicious'}
X_train, X_test, y_train, y_test = train_test_split(
    df[features], df['label'], test_size=0.2, random_state=42, stratify=df['label'])
model = Pipeline([
    ('imputer', SimpleImputer(strategy='median')),
    ('tree', DecisionTreeClassifier(max_depth=3, min_samples_leaf=3, random_state=42))
])
model.fit(X_train, y_train)
print('Training rows:', len(X_train), '| Test rows:', len(X_test))
print('Held-out accuracy:', round(accuracy_score(y_test, model.predict(X_test)), 3))
display(pd.DataFrame(confusion_matrix(y_test, model.predict(X_test), labels=['Normal','Suspicious']),
    index=['Actual Normal','Actual Suspicious'], columns=['Predicted Normal','Predicted Suspicious']))

"""## Q1. Baseline predictions with confidence (5 marks)
Confidence is the largest predicted class probability. Masking is applied before any table is displayed, including this baseline.
"""

def mask_ip(ip):
    parts = str(ip).split('.')
    return f'{parts[0]}.{parts[1]}.xxx.xxx' if len(parts) == 4 else '<MASKED_IP>'

def mask_account(account_id):
    text = str(account_id)
    return text[:4] + '***' + text[-2:] if len(text) >= 6 else '<MASKED_ACCOUNT>'

samples = pd.DataFrame([
    ['ACC-1001','192.168.10.24',0,10,0,40],
    ['ACC-1002','10.0.4.18',7,2,1,150],
    ['ACC-1003','172.16.8.90',1,15,0,720],
    ['ACC-1004','192.168.20.11',4,23,1,400],
    ['ACC-1005','10.1.1.9',2,9,0,80]
], columns=['account_id','ip_address'] + features)
samples['masked_account'] = samples['account_id'].apply(mask_account)
samples['masked_ip'] = samples['ip_address'].apply(mask_ip)
samples['prediction'] = model.predict(samples[features])
samples['confidence'] = model.predict_proba(samples[features]).max(axis=1)
baseline_table = samples[['masked_account','masked_ip'] + features + ['prediction','confidence']].copy()
display(baseline_table.round({'confidence':3}))
lowest = samples.loc[np.isclose(samples['confidence'], samples['confidence'].min())]
print('Lowest-confidence record(s):', ', '.join(lowest['masked_account']),
      '| confidence =', round(samples['confidence'].min(), 3))
print('Confidence is not certainty: leaf probabilities reflect a small training sample and may be poorly calibrated or wrong on new activity.')

"""## Q2. Feature importance and explanation (10 marks)"""

importance = pd.DataFrame({'feature':features,
    'importance':model.named_steps['tree'].feature_importances_}).sort_values('importance', ascending=False)
display(importance)
plt.figure(figsize=(7,4))
plt.bar(importance['feature'], importance['importance'], color='#24689b')
plt.title('Feature Importance for Login Alert')
plt.ylabel('Impurity-based importance')
plt.xticks(rotation=25)
plt.tight_layout()
plt.show()
explanations = {
    'failed_logins':'Repeated failed logins can indicate password guessing; the model uses this count to separate activity.',
    'login_hour':'The hour of login helps the model distinguish activity patterns, although unusual hours can be legitimate.',
    'new_device':'A new device can signal unfamiliar access, although a legitimate user can also change devices.',
    'download_mb':'Download volume helps distinguish transfer patterns; large downloads may merit verification.'}
for feature in importance.head(3)['feature']:
    print(feature + ': ' + explanations[feature])
print('Caution: importance describes global impurity reduction, not causation or a complete explanation of an individual prediction.')

"""## Q3. Controlled sensitivity test (10 marks)"""

baseline = samples.iloc[[4]].copy()
changed = baseline.copy()
changed['failed_logins'] = 8
assert [f for f in features if baseline.iloc[0][f] != changed.iloc[0][f]] == ['failed_logins']
comparison = pd.concat([baseline[features], changed[features]], ignore_index=True)
comparison.insert(0, 'case', ['Baseline', 'Changed'])
comparison['prediction'] = model.predict(comparison[features])
comparison['confidence'] = model.predict_proba(comparison[features]).max(axis=1)
display(comparison.round({'confidence':3}))
print('Only failed_logins changed, from 2 to 8; hour, device status and download volume stayed fixed.')
print('Prediction:', comparison.iloc[0]['prediction'], 'to', comparison.iloc[1]['prediction'])
print('Confidence:', round(comparison.iloc[0]['confidence'],3), 'to', round(comparison.iloc[1]['confidence'],3))
print('A changed class shows that this perturbation crosses a learned decision boundary.' if comparison.iloc[0]['prediction'] != comparison.iloc[1]['prediction'] else 'The class is unchanged for this perturbation; this does not establish insensitivity across all inputs.')
print('This is a local model response, not proof of an attack or a causal relationship.')

"""## Q4. Privacy masking and responsible-use rules (5 marks)"""

